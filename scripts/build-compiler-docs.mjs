#!/usr/bin/env node
/**
 * Publishes the compiler diagnostic registry and the IR compatibility policy
 * (FR-049-AC-11, FR-051-AC-12).
 *
 * The registry table is generated from `DIAGNOSTIC_CODES` rather than
 * maintained by hand, because a published list that drifts from the code is
 * worse than no list: a caller keys automation on it. The prose around it is
 * authored, and a test fails when the generated tables and the code disagree.
 *
 * Usage: node scripts/build-compiler-docs.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DISPOSITION_RANK } from "../src/compiler/compat/diff.mjs";
import { V1_1_ADDED_NODES } from "../src/compiler/compat/evolution.mjs";
import {
	DEFAULT_LIMITS,
	DIAGNOSTIC_CODES,
} from "../src/compiler/diagnostics.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const entries = Object.entries(DIAGNOSTIC_CODES)
	.map(([name, value]) => ({ name, ...value }))
	.sort((left, right) => (left.code < right.code ? -1 : 1));

const diagnosticsDocument = `---
id: ARCH-COMPILER-DIAGNOSTICS
title: "Compiler diagnostic registry"
status: normative
---
# Compiler diagnostic registry

Generated by \`scripts/build-compiler-docs.mjs\` from \`src/compiler/diagnostics.mjs\`.
A test fails when this document and the code disagree, because a published list
a caller keys automation on is worse than no list once it drifts.

## Two namespaces

\`agent-ix.compiler.*\` names a defect in what a package supplied to the compiler
— a manifest, a lock, a source file — or in how the caller invoked it.

\`agent-ix.semantic-ir.*\` names a defect in the *shape of an IR document*. Its
spellings are exactly the ones the issue #34 readers already emit, which is what
lets the compiler's reader, the issue #34 TypeScript reader and the Python
reader be compared code for code on every published negative case.

A \`constraint.diagnosticCode\` inside an emitted document is a datum for a
consumer to raise when that constraint fails. It is not a compiler diagnostic and
does not appear below.

## Blocking

A blocking diagnostic suppresses the IR file and forces a non-zero exit. Every
blocking code carries severity \`error\`; nothing is a blocking \`info\`.

## Codes

| Code | Severity | Blocking | Owner |
|---|---|---|---|
${entries
	.map(
		(entry) =>
			`| \`${entry.code}\` | ${entry.severity} | ${entry.blocking ? "yes" : "no"} | \`${entry.owner}\` |`,
	)
	.join("\n")}

## Limits

The compiler applies these defaults where a caller supplies no \`--limits\`
document. A \`--limits\` file is valid against
\`schema/semantic/v1/compiler-request.schema.json#/properties/limits\`.

| Limit | Default | Bounds |
|---|---|---|
| \`maxInputBytes\` | ${DEFAULT_LIMITS.maxInputBytes} | Any single manifest, mapping, profile, or lock |
| \`maxDepth\` | ${DEFAULT_LIMITS.maxDepth} | JSON nesting, canonicalisation, and nested diagnostic causes |
| \`maxNodes\` | ${DEFAULT_LIMITS.maxNodes} | Packages in a graph, and type definitions in a document |
| \`maxCollectionItems\` | ${DEFAULT_LIMITS.maxCollectionItems} | Any single array in an emitted or read document |
| \`maxDiagnostics\` | ${DEFAULT_LIMITS.maxDiagnostics} | Diagnostics reported; the list is sorted before it is truncated |

The four size limits each raise their own blocking diagnostic and stop the
analysis. Reaching \`maxDiagnostics\` is a non-blocking warning: the report is
truncated, but a run whose surviving diagnostics are all warnings still writes
its document.
`;

const policyDocument = `---
id: ARCH-IR-COMPATIBILITY-POLICY
title: "Semantic IR compatibility policy"
status: normative
---
# Semantic IR compatibility policy

Generated in part by \`scripts/build-compiler-docs.mjs\`; the disposition rank and
the added-node list are read from the code, and a test fails when they disagree.

## What may change within contract major version 1

1. A revision **may add an optional member**.
2. A revision **may widen a closed vocabulary**.
3. A revision **may not remove or retype a member**.
4. A revision **may not narrow a vocabulary**.

A revision that breaks rule 3 or rule 4 is classified \`breaking\` by
\`diffSemanticContract\`, whatever its version number says.

## How the three versions live in one file

\`schema/semantic/v1/semantic-ir.schema.json\` accepts \`1.0.0\`, \`1.1.0\`, and \`1.2.0\`
and discriminates on \`contractVersion\`. That is issue #34's decision, recorded
here rather than taken here: this policy cites the schema, and this repository's
compiler ticket changes no byte of it.

Contract \`1.1.0\` adds exactly these nodes:

${V1_1_ADDED_NODES.map((node) => `- \`${node}\``).join("\n")}

Contract \`1.2.0\` adds the scalar \`any\`, authored field presence, the model
members (\`supertypes\`, \`abstract\`, \`subsets\`, \`redefines\`, operation \`frame\`,
\`requires\`, \`ensures\`, document \`populations\`) and the ten object-type
construct kinds. The \`1.1.0\` → \`1.2.0\` revision is additive: a \`1.2.0\`
document may carry every \`1.1.0\` node, and a \`1.1.0\` document carrying a
\`1.2.0\` node is refused.

A version uplift is classified \`additive\` when — and only when — projecting the
new document back to the old version reproduces the old document byte for byte.
Counting each materialised member as its own change would classify the very
revision the contract declares additive as breaking.

## Projections

\`readIrAsContract(document, targetVersion, { dialect })\` projects a document
between the declared versions.

- Projecting **down** to \`1.0.0\` drops every \`1.1.0\`-only member and returns
  every dropped identity in \`loss\`. A projection that dropped them silently
  would let a \`1.0.0\` consumer believe it had the whole contract.
- Projecting **up** to \`1.1.0\` or \`1.2.0\` derives each field's multiplicity from its
  presence and requires the caller to declare the frontend dialect, because the
  schema forbids the \`1.0.0\` constant on a \`1.1.0\` document and no rule can
  recover which frontend produced it. Without one the projection is refused with
  \`agent-ix.compiler.MISSING_TARGET_DIALECT\`.
- Projecting to the document's own version returns it unchanged.
- Projecting to any other version is refused with
  \`agent-ix.compiler.UNKNOWN_CONTRACT_VERSION\`.

A projection carries \`source.digest\` and the whole \`package\` block verbatim: it
is a view of a compile's output, not a new compile.

## Disposition rank

Least restrictive to most. An aggregate is the most restrictive entry, and an
entry with per-target results is the most restrictive of those.

${DISPOSITION_RANK.map((value, index) => `${index + 1}. \`${value}\``).join("\n")}

## Absent inputs

Several families are not visible in an IR document at all — a profile's
authority, a mapping's edit direction, a reserved Protobuf number, a generated
name, the constraint vocabulary itself. Each arrives as a declared input, and
when an input is absent **the family is omitted and named in \`requiredGates\`**.
An absent input is a gap, never a \`patch\`: reporting "no change" for something
the diff could not look at is how a breaking release gets promoted.
`;

const outputs = {
	"docs/semantic-data-system/compiler-diagnostics.md": diagnosticsDocument,
	"docs/semantic-data-system/ir-compatibility-policy.md": policyDocument,
};

let stale = 0;
for (const [path, content] of Object.entries(outputs)) {
	const absolute = resolve(root, path);
	if (check) {
		let current = "";
		try {
			current = readFileSync(absolute, "utf8");
		} catch {
			current = "";
		}
		if (current !== content) {
			process.stderr.write(`stale: ${path}\n`);
			stale += 1;
		}
		continue;
	}
	writeFileSync(absolute, content);
}
if (check && stale > 0) process.exitCode = 1;
process.stdout.write(
	`${Object.keys(outputs).length} documents${check ? " checked" : " written"}\n`,
);
