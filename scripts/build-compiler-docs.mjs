#!/usr/bin/env node
/**
 * Publishes the compiler diagnostic registry (FR-049-AC-11).
 *
 * The registry table is generated from `DIAGNOSTIC_CODES` rather than
 * maintained by hand, because a published list that drifts from the code is
 * worse than no list: a caller keys automation on it. The prose around it is
 * authored, and a test fails when the generated tables and the code disagree.
 *
 * Usage: node scripts/build-compiler-docs.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
	DEFAULT_LIMITS,
	DIAGNOSTIC_CODES,
} from "../src/compiler/diagnostics.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const entries = Object.entries(DIAGNOSTIC_CODES)
	.map(([name, value]) => ({ name, ...value }))
	.sort((left, right) => (left.code < right.code ? -1 : 1));

const diagnosticsDocument = `---
id: ARCH-COMPILER-DIAGNOSTICS
title: "Compiler diagnostic registry"
status: normative
---
# Compiler diagnostic registry

Generated by \`scripts/build-compiler-docs.mjs\` from \`src/compiler/diagnostics.mjs\`.
A test fails when this document and the code disagree, because a published list
a caller keys automation on is worse than no list once it drifts.

## Two namespaces

\`agent-ix.compiler.*\` names a defect in what a package supplied to the compiler
— a manifest, a lock, a source file — or in how the caller invoked it.

\`agent-ix.semantic-ir.*\` names a defect in the *shape of an IR document*. Its
spellings are exactly the ones the issue #34 readers already emit, which is what
lets the compiler's reader, the issue #34 TypeScript reader and the Python
reader be compared code for code on every published negative case.

A \`constraint.diagnosticCode\` inside an emitted document is a datum for a
consumer to raise when that constraint fails. It is not a compiler diagnostic and
does not appear below.

## Blocking

A blocking diagnostic suppresses the IR file and forces a non-zero exit. Every
blocking code carries severity \`error\`; nothing is a blocking \`info\`.

## Codes

| Code | Severity | Blocking | Owner |
|---|---|---|---|
${entries
	.map(
		(entry) =>
			`| \`${entry.code}\` | ${entry.severity} | ${entry.blocking ? "yes" : "no"} | \`${entry.owner}\` |`,
	)
	.join("\n")}

## Limits

The compiler applies these defaults where a caller supplies no \`--limits\`
document. A \`--limits\` file is valid against
\`schema/semantic/v1/compiler-request.schema.json#/properties/limits\`.

| Limit | Default | Bounds |
|---|---|---|
| \`maxInputBytes\` | ${DEFAULT_LIMITS.maxInputBytes} | Any single manifest, mapping, profile, or lock |
| \`maxDepth\` | ${DEFAULT_LIMITS.maxDepth} | JSON nesting, canonicalisation, and nested diagnostic causes |
| \`maxNodes\` | ${DEFAULT_LIMITS.maxNodes} | Packages in a graph, and type definitions in a document |
| \`maxCollectionItems\` | ${DEFAULT_LIMITS.maxCollectionItems} | Any single array in an emitted or read document |
| \`maxDiagnostics\` | ${DEFAULT_LIMITS.maxDiagnostics} | Diagnostics reported; the list is sorted before it is truncated |

The four size limits each raise their own blocking diagnostic and stop the
analysis. Reaching \`maxDiagnostics\` is a non-blocking warning: the report is
truncated, but a run whose surviving diagnostics are all warnings still writes
its document.
`;

const outputs = {
	"docs/semantic-data-system/compiler-diagnostics.md": diagnosticsDocument,
};

let stale = 0;
for (const [path, content] of Object.entries(outputs)) {
	const absolute = resolve(root, path);
	if (check) {
		let current = "";
		try {
			current = readFileSync(absolute, "utf8");
		} catch {
			current = "";
		}
		if (current !== content) {
			process.stderr.write(`stale: ${path}\n`);
			stale += 1;
		}
		continue;
	}
	writeFileSync(absolute, content);
}
if (check && stale > 0) process.exitCode = 1;
process.stdout.write(
	`${Object.keys(outputs).length} documents${check ? " checked" : " written"}\n`,
);
