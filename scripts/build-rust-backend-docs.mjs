const outputs = [
	["docs/semantic-data-system/rust-backend.md", mapping],
	["docs/semantic-data-system/rust-backend-diagnostics.md", diagnostics],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [path, body] of outputs) {
	if (check) {
		let current = "";
		try {
			current = read(path);
		} catch {
			current = "";
		}
		if (current !== body) {
			process.stderr.write(
				`${path} is stale; run node scripts/build-rust-backend-docs.mjs\n`,
			);
			stale += 1;
		}
	} else {
		writeFileSync(resolve(root, path), body);
	}
	process.stdout.write(`${path}\n`);
}
if (stale > 0) process.exitCode = 1;
