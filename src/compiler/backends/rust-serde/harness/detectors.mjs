/** Runs the battery, optionally suppressing named cases (FR-062-AC-4). */
export function runDetectors(backend, options = {}) {
	const suppress = new Set(options.suppress ?? []);
	const results = [];
	for (const detector of DETECTORS) {
		if (suppress.has(detector.caseId)) {
			results.push({ caseId: detector.caseId, ok: true, suppressed: true });
			continue;
		}
		try {
			detector.run(backend);
			results.push({ caseId: detector.caseId, ok: true });
		} catch (error) {
			results.push({
				caseId: detector.caseId,
				ok: false,
				failure: String(error?.message ?? error),
			});
		}
	}
	return results;
}
