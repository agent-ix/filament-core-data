/** The nine kernel scalar names, read from the table rather than restated. */
function kernelScalars(table) {
	return table.rows
		.filter((row) => row.axis === "scalar")
		.map((row) => row.selector);
}

/** The kind names, read from the table. */
function kinds(table) {
	return table.rows
		.filter((row) => row.axis === "kind")
		.map((row) => row.selector);
}

function assert(condition, message) {
	if (condition !== true) throw new Error(message);
}

/**
 * Loads one backend copy.
 *
 * `directory` is the backend directory — the working tree's, or a scratch copy
 * the mutation harness made. Every module is imported from that directory, so
 * a mutated module is the one the detectors run against.
 */
export async function loadBackend(directory, options = {}) {
	const load = (name) => import(pathToFileURL(join(directory, name)).href);
	const [
		mapping,
		crate,
		diagnostics,
		names,
		graph,
		patterns,
		constraints,
		degradation,
		generator,
		properties,
	] = await Promise.all([
		load("mapping.mjs"),
		load("crate.mjs"),
		load("diagnostics.mjs"),
		load("names.mjs"),
		load("graph.mjs"),
		load("patterns.mjs"),
		load("constraints.mjs"),
		load("degradation.mjs"),
		load("generator.mjs"),
		load("properties.mjs"),
	]);
	return {
		directory,
		mapping,
		crate,
		diagnostics,
		names,
		graph,
		patterns,
		constraints,
		degradation,
		generator,
		properties,
		table: JSON.parse(
			readFileSync(join(directory, "mapping-table.json"), "utf8"),
		),
		publishedCodes: options.publishedCodes ?? [],
		licenseText: options.licenseText ?? "",
		bases: options.bases ?? [],
		baseline: options.baseline ?? new Map(),
		sources: readSources(directory),
	};
}

/** Every module's text, for the detectors that ask what a module names. */
function readSources(directory) {
	const sources = new Map();
	for (const name of readdirSync(directory)) {
		if (!name.endsWith(".mjs")) continue;
		sources.set(name, readFileSync(join(directory, name), "utf8"));
	}
	return sources;
}

/** The bytes one request emits, as one string. */
function bytesOf(backend, ir, outputRoot) {
	const request = backend.properties.requestForIr(ir, outputRoot);
	const result = backend.crate.emitCrate(request, {
		licenseText: backend.licenseText,
	});
	return [...result.files].map(([path, text]) => `${path}\n${text}`).join("");
}

/** The emission of one document, diagnostics included. */
function emitted(backend, ir, outputRoot = "generated") {
	return backend.crate.emitCrate(
		backend.properties.requestForIr(ir, outputRoot),
		{
			licenseText: backend.licenseText,
		},
	);
}

/** A document generated by the loaded copy's own generator. */
function document(backend, index = 0) {
	return backend.generator.generateDocument(
		backend.generator.DEFAULT_SEED,
		index,
	);
}

function mapped(backend, ir) {
	const { model, diagnostics } = backend.mapping.mapDocument(ir, {});
	assert(
		model !== undefined,
		`the generated document was refused: ${diagnostics.map((one) => one.code).join(", ")}`,
	);
	return model;
}

/** A minimal well-formed document carrying `types`. */
function documentOf(types) {
	return {
		contractVersion: "1.1.0",
		source: {
			identity: "ix://agent-ix/filament-core-data/source/typespec",
			version: "1.0.0",
			dialect: "typespec",
			digest: `sha256:${"0".repeat(64)}`,
		},
		package: {
			identity: "agent-ix/detector",
			version: "1.0.0",
			manifestDigest: `sha256:${"1".repeat(64)}`,
			mappingVersions: ["1.0.0"],
			profileVersions: ["1.0.0"],
			lockDigest: `sha256:${"2".repeat(64)}`,
		},
		types,
		occurrences: [],
		extensions: [],
	};
}

const NS = "ix://agent-ix/detector";

function scalarType(name, scalar, constraints = []) {
	return {
		identity: `${NS}/type/${name}`,
		displayName: name,
		kind: "scalar",
		roles: [],
		constraints,
		extensions: [],
		unknownPolicy: "reject",
		scalar,
	};
}

/** The operand a keyword takes over a subject, chosen so the operand is valid. */
function operandsFor(keyword, subject) {
	if (["min", "max", "exclusiveMin", "exclusiveMax"].includes(keyword)) {
		if (subject === "date") return { value: "2020-01-01" };
		if (subject === "datetime") return { value: "2020-01-01T00:00:00Z" };
		if (subject === "duration") return { value: "P1D" };
		if (subject === "number") return { value: 1.5 };
		return { value: 1 };
	}
	if (keyword === "minLength" || keyword === "maxLength") return { value: 2 };
	if (keyword === "pattern") return { regex: "^[a-z]+$" };
	if (keyword === "format") return { name: "agent-ix:plain-text" };
	if (keyword === "enumValues") {
		if (subject === "boolean") return { values: [true] };
		if (subject === "integer") return { values: [1] };
		if (subject === "number") return { values: [1.5] };
		return { values: ["a"] };
	}
	return {};
}

/** The resolved subject an applicability entry names. */
function resolvedFor(subject, table) {
	return kernelScalars(table).includes(subject)
		? { kind: "scalar", scalar: subject }
		: { kind: subject };
}

