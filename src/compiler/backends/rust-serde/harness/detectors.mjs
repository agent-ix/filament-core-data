/**
 * The detector battery (FR-062 "Mutations", FR-062-AC-1).
 *
 * One detector per test case. Each is a function of a *loaded backend* rather
 * than of the checked-out one, so the same assertion runs twice: the suite runs
 * it against the modules in the working tree, and the mutation harness runs it
 * against a mutated scratch copy. A mutation is detected when a detector that
 * passes on the pristine copy fails on the mutant.
 *
 * Writing the assertion once is the point. A detector the suite does not run is
 * a mutation score nobody earned, and a case the harness does not run is a
 * detection claim nobody checked; the register binds the two by name, and
 * `cli.mjs mutations --check` fails when a detector names a case the suite does
 * not carry.
 *
 * The oracles are the mapping table, the applicability table and the diagnostic
 * registry — the artefacts that *declare* the mapping — never the emitter's own
 * output. The one exception is the corpus-bytes detector, which compares a
 * mutant against the pristine emitter and is a change detector by construction;
 * it is named as such and no branch-register row rests on it alone.
 */

